class Contours(BasePen):
    def __init__(self, glyphs):
        super().__init__(glyphs)
        self.paths = []

    def _moveTo(self, p):
        self.paths.append([p])

    def _lineTo(self, p):
        self.paths[-1].append(p)

    def _curveToOne(self, b, c, d):
        def curve(a, b, c, d, depth=0):
            chord = ((d[0] - a[0]) ** 2 + (d[1] - a[1]) ** 2) ** 0.5
            polygon = sum(((v[0] - u[0]) ** 2 + (v[1] - u[1]) ** 2) ** 0.5
                          for u, v in [(a, b), (b, c), (c, d)])
            if polygon - chord < 0.5 or depth == 12:
                self.paths[-1].append(d)
                return
            def mid(u, v):
                return ((u[0] + v[0]) / 2, (u[1] + v[1]) / 2)
            ab, bc, cd = mid(a, b), mid(b, c), mid(c, d)
            abc, bcd = mid(ab, bc), mid(bc, cd)
            m = mid(abc, bcd)
            curve(a, ab, abc, m, depth + 1)
            curve(m, bcd, cd, d, depth + 1)
        curve(self._getCurrentPoint(), b, c, d)

    def _closePath(self):
        pass

    def _endPath(self):
        pass


def main():
    fonts = {}
    for style, file in [("roman", "c0648bt_.pfb"), ("italic", "c0649bt_.pfb")]:
        glyphs = T1Font(f"/usr/share/fonts/X11/Type1/{file}").getGlyphSet()
        table = {}
        for name in sorted(glyphs):
            char = agl.toUnicode(name)
            if len(char) != 1:
                continue
            pen = Contours(glyphs)
            glyphs[name].draw(pen)
            table[char] = {"advance": glyphs[name].width / 1000,
                           "contours": [[[round(x / 1000, 5), round(-y / 1000, 5)]
                                         for x, y in path] for path in pen.paths]}
        fonts[style] = table
    data = json.dumps(fonts, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
    source = "// Generated by tools/factory/card_font.py from Bitstream Charter Type 1.\n"
    source += "// Factory-only font data; the app does not link this target.\n"
    source += "\n".join(("// " + line).rstrip() for line in LICENSE.splitlines()) + "\nimport Foundation\n\n"
    source += "struct CardGlyph: Decodable, Sendable { let advance: Double; let contours: [[[Double]]] }\n"
    source += "enum Charter {\n    static let fonts = try! JSONDecoder().decode([String: [String: CardGlyph]].self, from: Data(data.utf8))\n"
    source += '    private static let data = #"""\n' + data + '\n"""#\n}\n'
    (ROOT / "Sources/FigureRig/Charter.swift").write_text(source)


if __name__ == "__main__":
    main()
