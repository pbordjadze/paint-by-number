/// One sound of the hidden modes (painting-company row 381): what `EraSynth.samples` makes and
/// `SoundPlayer` plays as one buffer. Foundation alone, so `tools/sounds/render.sh` makes the same
/// samples off the device.
nonisolated enum EraVoice: Hashable, Sendable {
    /// A step of the year wheel: a music box's tine, `step` 0…11 up the Moon's scale an octave
    /// above it, lower the further back the year.
    case tick(step: Int)
    /// An era's year clicking into place on the wheel: the Moon's bell with a star over it.
    case lit(step: Int)
    /// A passage between eras, whole, timed to its drawing (`EraPassage`).
    case passage(EraPassageSound)
    /// Watercolor: a wash laid, the brush's water on the paper and the tune's note under it.
    case wash(Sky, index: Int)
    /// Watercolor: water dropped on dry paper.
    case drop(variant: Int)
    /// Watercolor: water dropped on a laid wash, and the bloom's shimmer as it spreads.
    case bloom(index: Int, variant: Int)
    /// Watercolor: the sheet dry again, a star an octave above the tune's last note.
    case dried(index: Int)
    /// Watercolor: the painting finished, a last wash and the sky's run.
    case finale(Sky)
}

/// The passages' sounds, one for each way `EraPassage` draws one.
nonisolated enum EraPassageSound: Hashable, Sendable {
    /// Tiles set over the screen and lifted: the way to Paint by Mosaic, and The Frame's both ways.
    case tiles(Sky)
    /// The nave's dark and the rose window's light: Stained Glass's, both ways.
    case nave
    /// Water flooding the screen and drying: Watercolor's, both ways.
    case wash(Sky)
    /// Home from Paint by Mosaic: the tiles set, let go, the crescent rising and five stars.
    case wayBack
    /// Reduce Motion's dim: one chord.
    case still(Sky)
}

/// The hidden modes' sounds, synthesized as the app's are (`ToneSynth`; no audio assets, nothing
/// generated by a model): the same kalimba and celesta on the same scales, with three voices of
/// their own made from how the things sound: a music box's tine, a glass tessera struck, and
/// water, made of bubbles ringing as they form, after van den Doel's physically based liquid
/// sounds (2005), the way real water sounds. Every sound is the same at every launch.
nonisolated enum EraSynth {
    static let sampleRate = 44_100.0

    /// `SoundPlayer.sunScale` and `moonScale`, which `EraSoundsTests` holds these to.
    static let sunScale: [Double] = [293.66, 329.63, 369.99, 440.00, 493.88, 587.33, 659.26, 739.99, 880.00, 987.77, 1174.66, 1318.51]
    static let moonScale: [Double] = [246.94] + sunScale.dropLast()

    static func scale(of sky: Sky) -> [Double] { sky == .sun ? sunScale : moonScale }

    /// `EraPassage`'s and `EraWayBack`'s times, which the passages' sounds keep to
    /// (`EraSoundsTests` holds them to the drawing's).
    nonisolated enum Times {
        static let wait = 0.45, cover = 1.25, hold = 0.25, lift = 1.0
        static var total: Double { wait + cover + hold + lift }
        nonisolated enum WayBack {
            static let cover = 0.55, fall = 0.9, still = 0.45
            static var laid: Double { Times.wait + cover }
            static var fallen: Double { laid + fall }
            static var clears: Double { fallen + still }
            /// When the five stars come out (`EraWayBack.sky`).
            static func star(_ index: Int) -> Double { fallen - 0.25 + 0.11 * Double(index) }
        }
    }

    static func samples(of voice: EraVoice, sampleRate sr: Double = sampleRate) -> [Float] {
        switch voice {
        case let .tick(step): tick(step: clamped(step), sr: sr)
        case let .lit(step): lit(step: clamped(step), sr: sr)
        case let .passage(sound): passage(sound, sr: sr)
        case let .wash(sky, index): wash(sky: sky, index: clamped(index), sr: sr)
        case let .drop(variant): drop(variant: variant, sr: sr)
        case let .bloom(index, variant): bloom(index: clamped(index), variant: variant, sr: sr)
        case let .dried(index): dried(index: clamped(index), sr: sr)
        case let .finale(sky): finale(sky: sky, sr: sr)
        }
    }

    private static func clamped(_ i: Int) -> Int { min(max(i, 0), moonScale.count - 1) }

    // MARK: The wheel

    private static func tick(step: Int, sr: Double) -> [Float] {
        var mix = Mix(seconds: 0.5, sr: sr)
        mix.add(tine(frequency: 2 * moonScale[step], sr: sr, seed: UInt64(step)), at: 0, gain: 1)
        return mix.samples
    }

    private static func lit(step: Int, sr: Double) -> [Float] {
        var mix = Mix(seconds: 1.8, sr: sr)
        let third = min(step + 2, moonScale.count - 1)
        mix.add(ToneSynth.celesta(frequency: moonScale[step], sampleRate: sr), at: 0, gain: 0.26)
        mix.add(ToneSynth.celesta(frequency: moonScale[third], sampleRate: sr), at: 0.03, gain: 0.14)
        mix.add(ToneSynth.twinkle(frequency: 2 * moonScale[step], sampleRate: sr), at: 0.06, gain: 0.12)
        return mix.samples
    }

    // MARK: Passages

    private static func passage(_ sound: EraPassageSound, sr: Double) -> [Float] {
        typealias T = Times
        var mix = Mix(seconds: T.total + 1.6, sr: sr)
        var random = SplitMix64(seed: 0x7061_7373)
        switch sound {
        case let .tiles(sky):
            let scale = scale(of: sky)
            // The courses set from the bottom's middle out, more tiles in each wider course: a
            // patter of tesserae on the scale an octave up, quickening as it spreads.
            let set = 26
            for k in 0..<set {
                let u = (Double(k) + random.unit()) / Double(set)
                let note = 2 * scale[5 + Int(random.unit() * 7) % 7]
                mix.add(tessera(frequency: note, sr: sr, seed: random.next()),
                        at: T.wait + T.cover * 0.78 * u.squareRoot(), gain: Float(0.045 + 0.03 * random.unit()))
            }
            // The bed whole: a low chord in the sky's voice.
            for (k, i) in [0, 2, 4].enumerated() {
                mix.add(note(sky, scale[i], sr: sr), at: T.wait + T.cover + 0.04 * Double(k), gain: 0.16)
            }
            // The tiles lifting away from the middle out, fewer and softer, rising.
            let lifted = 10
            let start = T.wait + T.cover + T.hold
            for k in 0..<lifted {
                let u = (Double(k) + random.unit()) / Double(lifted)
                mix.add(tessera(frequency: 2 * scale[3 + k * 8 / lifted], sr: sr, seed: random.next()),
                        at: start + T.lift * 0.7 * u.squareRoot(), gain: 0.03)
            }
            mix.add(note(sky, scale[7], sr: sr), at: start + T.lift * 0.75, gain: 0.11)
        case .nave:
            // The nave's dark: a low fifth of the Moon's home note, swelling as the dark comes
            // and lifting with it.
            let darkest = T.cover * 0.8, until = T.cover + T.hold - darkest
            mix.add(drone(frequency: moonScale[0] / 2, attack: darkest, sustain: until, release: T.lift * 0.9, sr: sr), at: T.wait, gain: 0.05)
            mix.add(drone(frequency: moonScale[3] / 2, attack: darkest, sustain: until, release: T.lift * 0.9, sr: sr), at: T.wait, gain: 0.035)
            // The rose window's light coming: glass bells up the Moon's scale, and its heart.
            let light = T.wait + T.cover * 0.45
            mix.add(ToneSynth.celesta(frequency: moonScale[0], sampleRate: sr), at: light, gain: 0.13)
            let rose = [3, 5, 7, 8, 10]
            let span = T.cover * 0.55 + T.hold * 0.5
            for (k, i) in rose.enumerated() {
                mix.add(ToneSynth.twinkle(frequency: 2 * moonScale[i], sampleRate: sr),
                        at: light + span * Double(k) / Double(rose.count), gain: Float(0.09 + 0.012 * Double(k)))
            }
            let full = T.wait + T.cover + T.hold
            for (k, i) in [4, 6, 9].enumerated() {
                mix.add(ToneSynth.celesta(frequency: moonScale[i], sampleRate: sr), at: full + 0.05 * Double(k), gain: 0.1)
            }
            mix.add(ToneSynth.twinkle(frequency: 2 * moonScale[11], sampleRate: sr), at: full + 0.3, gain: 0.06)
        case let .wash(sky):
            // Water flooding in as the wash does (eased over the cover), standing, and drying away.
            let flood = { (t: Double) -> Double in
                let x = t - T.wait
                if x < 0 { return 0 }
                if x < T.cover { return 0.25 + 0.75 * ease(x / T.cover) }
                if x < T.cover + T.hold { return 1 }
                return max(0, 1 - ease((x - T.cover - T.hold) / (T.lift * 0.8)))
            }
            stream(into: &mix, from: T.wait, to: T.total, rate: { 260 * flood($0) },
                   radii: 0.7...3.2, gain: 0.016, random: &random)
            bed(into: &mix, from: T.wait, to: T.total, level: { 0.022 * flood($0) }, random: &random)
            for (k, at) in [0.08, 0.42, 0.85].enumerated() {
                mix.add(bubble(radius: 3.2 + 0.4 * Double(k), rise: 0.5, sr: sr), at: T.wait + at, gain: 0.1)
            }
            mix.add(note(sky, scale(of: sky)[4], sr: sr), at: T.wait + T.cover + T.hold + T.lift * 0.55, gain: 0.13)
        case .wayBack:
            typealias W = T.WayBack
            // The wall set quickly, on the Moon's scale.
            let set = 18
            for k in 0..<set {
                let u = (Double(k) + random.unit()) / Double(set)
                mix.add(tessera(frequency: 2 * moonScale[5 + Int(random.unit() * 7) % 7], sr: sr, seed: random.next()),
                        at: T.wait + W.cover * 0.78 * u.squareRoot(), gain: Float(0.04 + 0.025 * random.unit()))
            }
            // Let go from the top courses down: loosening, each a little lower.
            let fallen = 16
            for k in 0..<fallen {
                let u = (Double(k) + random.unit()) / Double(fallen)
                let i = 10 - Int(u * 8)
                mix.add(tessera(frequency: 2 * moonScale[i], sr: sr, seed: random.next()),
                        at: W.laid + W.fall * 0.7 * u, gain: Float(0.03 + 0.015 * random.unit()))
            }
            // The crescent rising as the courses over it go.
            for (k, i) in [2, 4, 7].enumerated() {
                mix.add(ToneSynth.celesta(frequency: moonScale[i], sampleRate: sr), at: W.laid + W.fall * (0.3 + 0.1 * Double(k)), gain: 0.15)
            }
            // Five stars, as each comes out.
            for (k, i) in [11, 9, 10, 8, 7].enumerated() {
                mix.add(ToneSynth.twinkle(frequency: 2 * moonScale[i], sampleRate: sr), at: W.star(k), gain: 0.09)
            }
            // The night clearing over the gallery.
            for (k, i) in [0, 3, 4].enumerated() {
                mix.add(ToneSynth.celesta(frequency: moonScale[i], sampleRate: sr), at: W.clears + 0.06 * Double(k), gain: 0.1)
            }
        case let .still(sky):
            for (k, i) in [0, 2, 4].enumerated() {
                mix.add(note(sky, scale(of: sky)[i], sr: sr), at: T.wait + T.cover * 0.5 + 0.05 * Double(k), gain: 0.14)
            }
        }
        return mix.samples
    }

    // MARK: Watercolor

    private static func wash(sky: Sky, index: Int, sr: Double) -> [Float] {
        var mix = Mix(seconds: 1.8, sr: sr)
        var random = SplitMix64(seed: 0x7761_7368 &+ UInt64(index))
        // The brush's water spreading over the area: a short swell of small bubbles, the
        // paper's hush under them.
        let swell = { (t: Double) -> Double in t < 0.1 ? t / 0.1 : max(0, 1 - (t - 0.1) / 0.4) }
        stream(into: &mix, from: 0, to: 0.55, rate: { 300 * swell($0) }, radii: 0.5...1.8, gain: 0.014, random: &random)
        bed(into: &mix, from: 0, to: 0.55, level: { 0.03 * swell($0) }, random: &random)
        mix.add(note(sky, scale(of: sky)[index], sr: sr), at: 0.03, gain: sky == .sun ? 0.2 : 0.17)
        return mix.samples
    }

    private static func drop(variant: Int, sr: Double) -> [Float] {
        var mix = Mix(seconds: 0.4, sr: sr)
        var random = SplitMix64(seed: 0x6472_6F70 &+ UInt64(variant & 7))
        dropOnto(&mix, at: 0, gain: 0.22, random: &random, sr: sr)
        return mix.samples
    }

    private static func bloom(index: Int, variant: Int, sr: Double) -> [Float] {
        var mix = Mix(seconds: 1.2, sr: sr)
        var random = SplitMix64(seed: 0x626C_6F6F &+ UInt64(variant & 7))
        dropOnto(&mix, at: 0, gain: 0.17, random: &random, sr: sr)
        // The bloom: pigment pushed out in a ring, a star and another just above it.
        let above = min(index + 2, moonScale.count - 1)
        mix.add(ToneSynth.twinkle(frequency: 2 * moonScale[index], sampleRate: sr), at: 0.12, gain: 0.08)
        mix.add(ToneSynth.twinkle(frequency: 2 * moonScale[above], sampleRate: sr), at: 0.3, gain: 0.05)
        return mix.samples
    }

    private static func dried(index: Int, sr: Double) -> [Float] {
        var mix = Mix(seconds: 0.9, sr: sr)
        mix.add(ToneSynth.twinkle(frequency: 2 * moonScale[index], sampleRate: sr), at: 0, gain: 0.06)
        return mix.samples
    }

    private static func finale(sky: Sky, sr: Double) -> [Float] {
        var mix = Mix(seconds: 3.4, sr: sr)
        var random = SplitMix64(seed: 0x6669_6E65)
        let swell = { (t: Double) -> Double in t < 0.3 ? t / 0.3 : max(0, 1 - (t - 0.3) / 1.3) }
        stream(into: &mix, from: 0, to: 1.6, rate: { 180 * swell($0) }, radii: 0.6...2.4, gain: 0.012, random: &random)
        let scale = scale(of: sky)
        switch sky {
        case .sun:
            for (k, i) in [4, 5, 7, 9, 11].enumerated() {
                mix.add(note(.sun, scale[i], sr: sr), at: 0.15 + 0.1 * Double(k), gain: 0.16)
            }
            for i in [5, 7, 9] { mix.add(note(.sun, scale[i], sr: sr), at: 0.8, gain: 0.15) }
        case .moon:
            for (k, i) in [7, 5, 4, 2, 0].enumerated() {
                mix.add(note(.moon, scale[i], sr: sr), at: 0.15 + 0.14 * Double(k), gain: 0.15)
            }
            for i in [0, 1, 3, 4] { mix.add(note(.moon, scale[i], sr: sr), at: 1.0, gain: 0.13) }
            mix.add(ToneSynth.twinkle(frequency: 2 * scale[5], sampleRate: sr), at: 1.35, gain: 0.09)
        }
        return mix.samples
    }

    // MARK: Voices

    private static func note(_ sky: Sky, _ frequency: Double, sr: Double) -> [Float] {
        sky == .sun ? ToneSynth.kalimba(frequency: frequency, sampleRate: sr)
                    : ToneSynth.celesta(frequency: frequency, sampleRate: sr)
    }

    /// A music box's tine: a pure, quickly fading pitch with a bright inharmonic glint and the
    /// pin's click.
    static func tine(frequency f: Double, sr: Double, seed: UInt64) -> [Float] {
        let length = 0.45, n = Int(sr * length)
        var out = [Float](repeating: 0, count: n)
        var noise = SplitMix64(seed: seed ^ 0x7469_6E65)
        var lowpassed = 0.0
        for i in 0..<n {
            let t = Double(i) / sr
            let attack = min(1, t / 0.0015)
            let body = sin(2 * .pi * f * t) * exp(-t * 9)
            let glint = 0.12 * sin(2 * .pi * 5.93 * f * t) * exp(-t * 60)
            lowpassed += 0.5 * (noise.unit() - lowpassed)
            let pin = 0.05 * lowpassed * exp(-t * 400)
            let tail = min(1, (length - t) / 0.08)
            out[i] = Float((attack * (body + glint) + pin) * tail)
        }
        return out
    }

    /// A glass tessera set down on its bed: a short tick and three modes of a small stiff plate,
    /// gone in a quarter second.
    static func tessera(frequency f: Double, sr: Double, seed: UInt64) -> [Float] {
        let length = 0.3, n = Int(sr * length)
        var out = [Float](repeating: 0, count: n)
        var noise = SplitMix64(seed: seed)
        let detune = 1 + 0.004 * noise.unit()
        var lowpassed = 0.0
        for i in 0..<n {
            let t = Double(i) / sr
            let attack = min(1, t / 0.0008)
            let ring = sin(2 * .pi * f * detune * t) * exp(-t * 26)
                + 0.45 * sin(2 * .pi * 2.32 * f * t) * exp(-t * 42)
                + 0.2 * sin(2 * .pi * 4.25 * f * t) * exp(-t * 75)
            lowpassed += 0.35 * (noise.unit() - lowpassed)
            let tick = 0.35 * lowpassed * exp(-t * 900)
            let tail = min(1, (length - t) / 0.05)
            out[i] = Float((attack * ring + tick) * tail * 0.5)
        }
        return out
    }

    /// One bubble ringing as it forms in water (Minnaert's resonance; van den Doel 2005): `radius`
    /// in millimetres sets its pitch (3.26 m·Hz over the radius), its damping, and its pitch
    /// rising as it nears the surface, by `rise` (a falling drop's bubble rises most: the plink).
    static func bubble(radius: Double, rise: Double, sr: Double) -> [Float] {
        let f0 = 3260 / radius
        let decay = 0.042 * f0 + 0.0011 * pow(f0, 1.5)
        let length = min(0.25, 7 / decay), n = Int(sr * length)
        var out = [Float](repeating: 0, count: n)
        var phase = 0.0
        for i in 0..<n {
            let t = Double(i) / sr
            let f = f0 * (1 + rise * decay * t)
            phase += 2 * .pi * f / sr
            let attack = min(1, t / 0.0006)
            out[i] = Float(attack * sin(phase) * exp(-t * decay))
        }
        return out
    }

    /// A drop falling on paper: its own bubble and the few small ones its splash makes.
    private static func dropOnto(_ mix: inout Mix, at start: Double, gain: Float, random: inout SplitMix64, sr: Double) {
        mix.add(bubble(radius: 2.6 + 1.2 * random.unit(), rise: 0.45 + 0.2 * random.unit(), sr: sr), at: start, gain: gain)
        for _ in 0..<3 {
            mix.add(bubble(radius: 0.8 + 0.8 * random.unit(), rise: 0.15, sr: sr),
                    at: start + 0.015 + 0.05 * random.unit(), gain: gain * 0.22)
        }
    }

    /// Running water: bubbles at random, `rate(t)` a second, their radii spread log-evenly over
    /// `radii` (more small than large), each as loud as it is large.
    private static func stream(into mix: inout Mix, from start: Double, to end: Double, rate: (Double) -> Double,
                               radii: ClosedRange<Double>, gain: Float, random: inout SplitMix64) {
        let peak = stride(from: start, to: end, by: 0.01).map(rate).max() ?? 0
        guard peak > 0 else { return }
        var t = start
        let low = log(radii.lowerBound), high = log(radii.upperBound)
        while true {
            t += -log(max(1e-9, random.unit())) / peak
            guard t < end else { break }
            guard random.unit() < rate(t) / peak else { continue }
            let r = exp(low + (high - low) * random.unit() * random.unit())
            mix.add(bubble(radius: r, rise: 0.1 * random.unit(), sr: mix.sr), at: t,
                    gain: gain * Float(r / radii.upperBound).squareRoot() * Float(0.6 + 0.4 * random.unit()))
        }
    }

    /// The hush of water moving over paper: soft noise, low-passed twice, at `level(t)`.
    private static func bed(into mix: inout Mix, from start: Double, to end: Double, level: (Double) -> Double,
                            random: inout SplitMix64) {
        var a = 0.0, b = 0.0
        let first = Int(start * mix.sr), last = min(mix.samples.count, Int(end * mix.sr))
        guard first < last else { return }
        for i in first..<last {
            a += 0.08 * (random.unit() - a)
            b += 0.08 * (a - b)
            mix.samples[i] += Float(b * 3 * level(Double(i) / mix.sr))
        }
    }

    /// A low, soft organ-like hum: the note and its octave and twelfth, a slow beat between two
    /// strings of it, swelling in over `attack`, held, and gone over `release`.
    private static func drone(frequency f: Double, attack: Double, sustain: Double, release: Double, sr: Double) -> [Float] {
        let length = attack + sustain + release, n = Int(sr * length)
        var out = [Float](repeating: 0, count: n)
        for i in 0..<n {
            let t = Double(i) / sr
            let swell = t < attack ? ease(t / attack) : t < attack + sustain ? 1 : 1 - ease((t - attack - sustain) / release)
            var s = 0.0
            for (detune, weight) in [(0.0, 0.6), (0.7, 0.4)] {
                let g = f + detune
                s += weight * (sin(2 * .pi * g * t) + 0.3 * sin(2 * .pi * 2 * g * t) + 0.1 * sin(2 * .pi * 3 * g * t))
            }
            out[i] = Float(s * swell)
        }
        return out
    }

    static func ease(_ x: Double) -> Double {
        let t = min(1, max(0, x))
        return t * t * (3 - 2 * t)
    }

    /// Sounds laid on one another, each at its own time and gain.
    nonisolated struct Mix {
        var samples: [Float]
        let sr: Double

        init(seconds: Double, sr: Double) {
            samples = Array(repeating: 0, count: Int(seconds * sr))
            self.sr = sr
        }

        mutating func add(_ sound: [Float], at time: Double, gain: Float) {
            let start = Int(time * sr)
            guard start >= 0, start < samples.count else { return }
            let count = min(sound.count, samples.count - start)
            for i in 0..<count { samples[start + i] += sound[i] * gain }
        }
    }
}

private extension SplitMix64 {
    /// A uniform draw in [0, 1).
    nonisolated mutating func unit() -> Double { Double(next() >> 11) / Double(1 << 53) }
}
