        else { Issue.record("The fixture must exercise atlas playback") }
        #expect(!pet.hint.isEmpty)
        for id in ["missing", "../fixture", "fixture.webp", "", "Fixture"] {
            #expect(MarginariumPet.named(id, bundle: bundle) == nil)
        }
    }

    @Test func atlasPlaybackIdlesWavesAndUsesOneStillResponseForReducedMotion() {
        let animation = SpriteAtlas.animation
        #expect(animation.idle.map(\.source) == (0..<6).map { .cell(.init(row: 0, column: $0)) })
        #expect(animation.actionFrames(reduceMotion: false).map(\.source)
                == (0..<4).map { .cell(.init(row: 3, column: $0)) })
        let still = animation.actionFrames(reduceMotion: true)
        #expect(still.count == 1)
        #expect(still.first?.source == .cell(.init(row: 3, column: 1)))
        #expect(still.first?.hold == .milliseconds(600))
    }
