/// Counts sheet decodes and how many overlap, standing in for the cache's loader.
private final class DecodeGauge: @unchecked Sendable {
    private let lock = NSLock()
    private var running = 0
    private var maximum = 0
    private var total = 0

    var started: Int { lock.withLock { total } }
    var peak: Int { lock.withLock { maximum } }

    /// Holds the decode open a moment, so decodes the cache failed to space out would overlap.
    func run<T>(_ decode: () -> T) -> T {
        lock.withLock {
            total += 1
            running += 1
            maximum = max(maximum, running)
        }
        defer { lock.withLock { running -= 1 } }
        Thread.sleep(forTimeInterval: 0.02)
        return decode()
    }
}

/// The WebP is colored geometry, generated by tools/tests/fixtures/make_sprite_atlas.py.
/// It belongs only to this test bundle, never to the app or a guardian's artwork.
@MainActor
struct SpriteAtlasTests {
    private var bundle: Bundle { Bundle(for: SpriteTestBundle.self) }

    private func fixtureURL() throws -> URL {
        try #require(bundle.url(forResource: "pet-fixture", withExtension: "webp"))
    }

    @Test func rectanglesFollowTheV2ContractAndRejectUnusedOrInvalidCells() {
        let counts = [6, 8, 8, 4, 5, 8, 6, 6, 6, 8, 8]
        #expect(counts.reduce(0, +) == 73)
        for (row, count) in counts.enumerated() {
            for column in 0..<8 {
                let rect = SpriteAtlas.Cell(row: row, column: column).rect
                if column < count {
                    #expect(rect == CGRect(x: column * 192, y: row * 208, width: 192, height: 208))
                } else { #expect(rect == nil) }
            }
        }
        for row in [-1, 11, Int.max, Int.min] {
            #expect(SpriteAtlas.Cell(row: row, column: 0).rect == nil)
        }
        for column in [-1, 8, Int.max, Int.min] {
            #expect(SpriteAtlas.Cell(row: 0, column: column).rect == nil)
        }
    }

    @Test func webPDecodesAndEveryCellKeepsItsPixelsAndOrientation() async throws {
        let url = try fixtureURL()
        let atlas = try #require(await Background.run { SpriteAtlas.load(at: url) })
        for (row, count) in SpriteAtlas.frameCounts.enumerated() {
            for column in 0..<count {
                let image = try #require(atlas.image(at: .init(row: row, column: column)))
                #expect(image.width == 192 && image.height == 208)
                let pixels = PixelReader(image)
                #expect(pixels[96, 104] == SIMD3(15 + row * 20, 11 + column * 27, 100))
                #expect(pixels[12, 12] == SIMD3(255, 255, 255))
                #expect(pixels[179, 195] == SIMD3(0, 0, 255))
                #expect(pixels[0, 0] == .zero)
            }
        }
        #expect(atlas.image(at: .init(row: 0, column: 6)) == nil)
        #expect(atlas.image(at: .init(row: 11, column: 0)) == nil)
    }

    /// A small player keeps only these: the idle loop's cells and the waving row, redrawn small.
    @Test func thumbnailsAreSmallCopiesOfExactlyTheCellsThePlayerShows() async throws {
        let url = try fixtureURL()
        let atlas = try #require(await Background.run { SpriteAtlas.load(at: url) })
        let thumbnails = try #require(atlas.thumbnails(maxPixelSize: 104))
        let played = (0..<6).map { SpriteAtlas.Cell(row: 0, column: $0) } + (0..<4).map { SpriteAtlas.Cell(row: 3, column: $0) }
        #expect(Set(thumbnails.keys) == Set(played))
        #expect(Set(SpriteAtlas.playedCells) == Set(played) && SpriteAtlas.playedCells.count == played.count)
        for (cell, image) in thumbnails {
            #expect(image.width == 96 && image.height == 104)
            #expect(PixelReader(image)[48, 52] == SIMD3(15 + cell.row * 20, 11 + cell.column * 27, 100))
        }
    }

    /// A 72 pt drawing on a 3x iPhone asks for 234 pixels, more than a cell holds. The copy must
    /// still be a bitmap of its own: a crop shares its sheet, and a page of drawings holding crops
    /// held twenty 13.4 MiB sheets.
    @Test func aCellBiggerThanItsDisplayIsStillCopiedAndNeverScaledUp() async throws {
        let url = try fixtureURL()
        let atlas = try #require(await Background.run { SpriteAtlas.load(at: url) })
        let large = try #require(atlas.thumbnails(maxPixelSize: 234))
        #expect(large.count == SpriteAtlas.playedCells.count)
        for (cell, image) in large {
            #expect(image.width == 192 && image.height == 208)
            #expect(ImageCache<URL>.cost(of: image) <= 192 * 208 * 4)
            #expect(PixelReader(image)[96, 104] == SIMD3(15 + cell.row * 20, 11 + cell.column * 27, 100))
            #expect(PixelReader(image)[0, 0] == .zero)
        }
    }

    @Test func missingCorruptAndWrongSizeSheetsFailWithoutFrames() async throws {
        let root = Fixtures.temporaryDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let cache = SpriteAtlasCache()
        let missing = root.appending(path: "missing.webp")
        #expect(await cache.frames(at: missing, maxPixelSize: 208) == nil)
        let corrupt = root.appending(path: "corrupt.webp")
        try Data("not an image".utf8).write(to: corrupt)
        #expect(await cache.frames(at: corrupt, maxPixelSize: 208) == nil)
        let url = try fixtureURL()
        let atlas = try #require(await Background.run { SpriteAtlas.load(at: url) })
        // v1, one pixel short, one cell, and transposed v2 dimensions are all invalid.
        for size in [(1536, 1872), (1535, 2288), (192, 208), (2288, 1536)] {
            let context = try #require(CGContext(
                data: nil, width: size.0, height: size.1, bitsPerComponent: 8, bytesPerRow: 0,
                space: CGColorSpace(name: CGColorSpace.sRGB)!,
                bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue))
            let image = try #require(context.makeImage())
            #expect(SpriteAtlas(sheet: image) == nil)
        }
        let cropped = try #require(atlas.sheet.cropping(to: CGRect(x: 0, y: 0, width: 192, height: 208)))
        let wrong = root.appending(path: "wrong-size.png")
        try #require(ImageCodec.pngData(cropped)).write(to: wrong)
        #expect(await cache.frames(at: wrong, maxPixelSize: 208) == nil)
        #expect(!cache.isLoading)
        #expect(cache.decodedBytes == 0)
    }

    private func waitUntilEmpty(_ cache: SpriteAtlasCache) async throws {
        var waited = 0
        while cache.decodedBytes > 0, waited < 200 {
            try await Task.sleep(for: .milliseconds(10))
            waited += 1
        }
    }

    @Test func concurrentReadersAndLaterReadersShareOneDecodeUntilMemoryWarning() async throws {
        let fixture = try fixtureURL()
        let gauge = DecodeGauge()
        let cache = SpriteAtlasCache(sheet: { _ in gauge.run { SpriteAtlas.load(at: fixture) } })
        async let firstLoad = cache.frames(at: fixture, maxPixelSize: 208)
        async let secondLoad = cache.frames(at: fixture, maxPixelSize: 208)
        let (firstResult, secondResult) = await (firstLoad, secondLoad)
        let first = try #require(firstResult)
        let second = try #require(secondResult)
        #expect(gauge.started == 1)
        #expect(!cache.isLoading)
        #expect(first.count == SpriteAtlas.playedCells.count)
        for cell in SpriteAtlas.playedCells { #expect(first[cell] === second[cell]) }
        let again = try #require(await cache.frames(at: fixture, maxPixelSize: 208))
        #expect(gauge.started == 1)
        for cell in SpriteAtlas.playedCells { #expect(first[cell] === again[cell]) }
        #expect(cache.decodedBytes > 0)
        NotificationCenter.default.post(name: UIApplication.didReceiveMemoryWarningNotification, object: nil)
        try await waitUntilEmpty(cache)
        #expect(cache.decodedBytes == 0)
        let reloaded = try #require(await cache.frames(at: fixture, maxPixelSize: 208))
        #expect(gauge.started == 2)
        for cell in SpriteAtlas.playedCells { #expect(first[cell] !== reloaded[cell]) }
    }

    /// The contents page opens on twenty guardians' drawings at once. Their sheets decode a couple at
    /// a time, each exactly once, and what stays is their small frames: an eighth of the 281 MB that
    /// holding their sheets took.
    @Test(arguments: [1, 2])
    func aPageOfTwentyDrawingsDecodesFewAtATimeAndKeepsOnlySmallFrames(concurrentDecodes: Int) async throws {
        let fixture = try fixtureURL()
        let gauge = DecodeGauge()
        let cache = SpriteAtlasCache(concurrentDecodes: concurrentDecodes,
                                     sheet: { _ in gauge.run { SpriteAtlas.load(at: fixture) } })
        let urls = (0..<20).map { URL(fileURLWithPath: "/pets/pet-\($0).webp") }
        let sheetBytes = SpriteAtlas.width * SpriteAtlas.height * 4
        var pages: [[SpriteAtlas.Cell: CGImage]] = []
        await withTaskGroup(of: [SpriteAtlas.Cell: CGImage]?.self) { group in
            for url in urls {
                group.addTask { await cache.frames(at: url, maxPixelSize: 234) }
            }
            for await frames in group { if let frames { pages.append(frames) } }
        }
        #expect(pages.count == 20)
        #expect(gauge.started == 20)
        #expect(gauge.peak <= concurrentDecodes)
        #expect(!cache.isLoading)
        for frames in pages {
            #expect(frames.count == SpriteAtlas.playedCells.count)
            let bytes = frames.values.reduce(0) { $0 + ImageCache<URL>.cost(of: $1) }
            #expect(bytes * 8 < sheetBytes, "A drawing's frames are an eighth of its sheet at most.")
        }
        #expect(cache.decodedBytes <= SpriteAtlasCache.costLimit)
        #expect(cache.decodedBytes * 8 < urls.count * sheetBytes)
    }

    @Test func framesAreDrawnToTheSizeAskedForAndNeverBeyondTheCell() async throws {
        let fixture = try fixtureURL()
        let cache = SpriteAtlasCache()
        // A margin pet, a card, a 72 pt drawing at 3x and a brief's: rounded up to 16, at most 208.
        for (asked, long) in [(104, 112), (156, 160), (170, 176), (234, 208), (624, 208), (0, 16)] {
            let frames = try #require(await cache.frames(at: fixture, maxPixelSize: asked))
            #expect(frames.values.allSatisfy { $0.height == long && $0.width <= long })
        }
    }

    @Test func petLookupKeepsImagesetsAndFindsOnlyBundledAtlases() throws {
        #expect(MarginariumPet.named("pip")?.animation.idle.first?.source == .asset("pip-idle-0"))
        #expect(MarginariumPet.named("colophon")?.animation.idle.first?.source == .asset("colophon-idle-0"))
        #expect(Bundle.main.url(forResource: "pet-fixture", withExtension: "webp") == nil)
